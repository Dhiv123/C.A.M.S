class CAMSClassifier:
    def __init__(self):
        self.intent_classifier = None
        self.vectorizer = None
        self.bridging_classifier = None
        self.isolation_forest = None
        self.is_trained = False
        self.train_metrics = {}

        self.medical_terms = [
            'patient', 'medication', 'diagnosis', 'treatment', 'symptoms', 'prescription',
            'lab', 'test', 'results', 'vitals', 'blood', 'pressure', 'glucose', 'hemoglobin',
            'appointment', 'encounter', 'procedure', 'surgery', 'condition', 'allergy',
            'dose', 'mg', 'ml', 'hospital', 'clinic', 'doctor', 'nurse', 'health'
        ]

        self.locator_phrases = [
            'lost', 'previous', 'example', 'repeat', 'forgot', 'earlier', 'queries',
            'retrieve', 'show me', 'what were', 'workflow', 'history', 'accumulated',
            'context', 'intermediate', 'results', 'background', 'data accessed'
        ]

        self.aligner_phrases = [
            'search box', 'answer variable', 'response', 'output', 'display',
            'return', 'format', 'present', 'include', 'save in', 'enter in'
        ]

    def extract_linguistic_features(self, query):
        query_lower = query.lower()
        features = {}

        features['has_locator'] = sum(1 for phrase in self.locator_phrases if phrase in query_lower)
        features['has_aligner'] = sum(1 for phrase in self.aligner_phrases if phrase in query_lower)
        features['locator_ratio'] = features['has_locator'] / max(len(query.split()), 1)

        word_count = len(query.split())
        medical_count = sum(1 for term in self.medical_terms if term in query_lower)
        features['medical_density'] = medical_count / max(word_count, 1)
        features['has_medical_terms'] = int(medical_count > 0)

        patient_ids = re.findall(r'patient[_\s]*\d+', query_lower)
        features['patient_id_count'] = len(patient_ids)
        features['has_multiple_patient_ids'] = int(len(set(patient_ids)) > 1)

        bridging_words = ['saved under', 'mapped to', 'now', 'is now', 'refer to',
                         'transferred to', 'equals', 'aliased', 'redirect']
        features['bridging_indicators'] = sum(1 for word in bridging_words if word in query_lower)

        features['query_length'] = len(query)
        features['word_count'] = word_count
        features['has_question_mark'] = int('?' in query)
        features['is_imperative'] = int(query.strip().split()[0].lower() in
                                       ['show', 'display', 'give', 'list', 'provide', 'enter', 'save'])

        return features

    def build_feature_matrix(self, queries):
        tfidf_features = self.vectorizer.transform(queries).toarray()
        linguistic_features = []
        for query in queries:
            ling_feat = self.extract_linguistic_features(query)
            linguistic_features.append(list(ling_feat.values()))
        linguistic_features = np.array(linguistic_features)
        combined_features = np.hstack([tfidf_features, linguistic_features])
        return combined_features

    def classify_intent(self, query):

        if not self.is_trained:
            return {'intent': 'unknown', 'confidence': 0.0, 'blocked': False}

        query_combined = self.build_feature_matrix([query])
        prediction = self.intent_classifier.predict(query_combined)[0]

        # TEMPORARY FIX: Force bridging patterns to be MINJA
        if any(word in query.lower() for word in ['saved under', 'mapped to', 'is now', 'refer to', 'transferred to', 'now patient']):
            prediction = 'minja'
            confidence = 0.95
            blocked = True
        else:
            probabilities = self.intent_classifier.predict_proba(query_combined)[0]
            class_probs = dict(zip(self.intent_classifier.classes_, probabilities))
            confidence = max(probabilities)
            blocked = prediction in ['minja', 'mextra']

        return {
            'intent': prediction,
            'confidence': confidence,
            'blocked': blocked,
            'probabilities': class_probs if 'class_probs' in locals() else {}
        }

    def detect_bridging(self, text):
        """Detect if text contains bridging attack patterns"""
        if not self.bridging_classifier:
            return False
        text_vec = self.vectorizer.transform([text]).toarray()
        ling_feat = np.array([list(self.extract_linguistic_features(text).values())])
        combined = np.hstack([text_vec, ling_feat])
        is_bridging = self.bridging_classifier.predict(combined)[0]
        return bool(is_bridging)

    def scan_ltm_for_minja(self, ltm_memories):
        """FIXED: Scan LTM for MINJA bridging patterns - triggers on >= 1 bridging memory"""
        bridging_memories = []
        patient_ids = set()

        for memory in ltm_memories[-50:]:
            content = memory.get('content', '')
            reasoning = memory.get('reasoning', '')
            full_text = content + ' ' + reasoning
            is_bridging = self.detect_bridging(full_text)

            if is_bridging:
                bridging_memories.append(memory)
                patient_matches = re.findall(r'patient[_\s]*\d+', full_text.lower())
                patient_ids.update(patient_matches)

        # CHANGED: Trigger on >= 1 bridging memory instead of >= 3
        if len(bridging_memories) >= 1:
            is_anomalous = True
            if self.isolation_forest:
                features = []
                for mem in bridging_memories:
                    content = mem.get('content', '')
                    reasoning = mem.get('reasoning', '')
                    pids = len(set(re.findall(r'patient[_\s]*\d+', content.lower())))
                    features.append([
                        len(content),
                        len(reasoning),
                        pids,
                        sum(1 for term in self.medical_terms if term in content.lower())
                    ])

                # If only 1 feature vector, duplicate it to avoid scikit-learn issues
                if len(features) == 1:
                    features.append(features[0])

                anomaly_scores = -(self.isolation_forest.decision_function(features))

            else:
                is_anomalous = None

            return {
                'minja_detected': is_anomalous,
                'bridging_count': len(bridging_memories),
                'unique_patient_ids': len(patient_ids),
                'bridging_density': len(bridging_memories) / max(len(ltm_memories[-50:]), 1),
                'patient_ids_involved': list(patient_ids),
                'anomaly_score': float(np.mean(anomaly_scores)) if self.isolation_forest and len(features) > 0 else None,
                'memories_scanned': len(ltm_memories[-50:])
            }

        return {
            'minja_detected': False,
            'bridging_count': len(bridging_memories),
            'memories_scanned': len(ltm_memories[-50:])
        }

    def load_models(self, base_path):
        self.intent_classifier = joblib.load(f"{base_path}/intent_classifier.pkl")
        self.vectorizer = joblib.load(f"{base_path}/vectorizer.pkl")
        self.bridging_classifier = joblib.load(f"{base_path}/bridging_classifier.pkl")
        try:
            self.isolation_forest = joblib.load(f"{base_path}/isolation_forest.pkl")
        except:
            print("Warning: Isolation Forest not found")
        try:
            self.train_metrics = joblib.load(f"{base_path}/train_metrics.pkl")
        except:
            self.train_metrics = {}
        self.is_trained = True
        print("All models loaded successfully")


class CAMSDefense:
    def __init__(self, cams_classifier):
        self.cams = cams_classifier
        self.enabled = False
        self.quarantine = []
        self.blocked_queries_log = []
        self.ltm_scan_history = []
        self.defense_stats = {
            'total_queries': 0,
            'minja_blocked': 0,
            'mextra_blocked': 0,
            'legitimate_passed': 0,
            'false_positives': 0,
            'ltm_scans_performed': 0,
            'minja_patterns_detected': 0
        }

    def enable(self):
        self.enabled = True
        print("✓ CAMS Defense ENABLED")

    def disable(self):
        self.enabled = False
        print("✓ CAMS Defense DISABLED")

    def intercept_query(self, query, patient_id=None):
        self.defense_stats['total_queries'] += 1

        if not self.enabled:
            return {'allowed': True, 'query': query, 'reason': 'CAMS disabled'}

        classification = self.cams.classify_intent(query)

        if classification['blocked']:
            self.blocked_queries_log.append({
                'query': query,
                'intent': classification['intent'],
                'confidence': classification['confidence'],
                'patient_id': patient_id,
                'timestamp': pd.Timestamp.now()
            })

            if classification['intent'] == 'minja':
                self.defense_stats['minja_blocked'] += 1
            elif classification['intent'] == 'mextra':
                self.defense_stats['mextra_blocked'] += 1

            return {
                'allowed': False,
                'blocked': True,
                'intent': classification['intent'],
                'confidence': classification['confidence'],
                'reason': f"Query blocked: Detected {classification['intent'].upper()} attack pattern"
            }

        self.defense_stats['legitimate_passed'] += 1
        return {
            'allowed': True,
            'query': query,
            'intent': classification['intent'],
            'confidence': classification['confidence']
        }

    def filter_retrieval(self, ltm_results, query_classification):
        if not self.enabled:
            return ltm_results
        filtered = [m for m in ltm_results if m.get('id') not in [q['id'] for q in self.quarantine]]
        if query_classification.get('intent') == 'legitimate':
            filtered = filtered[:5]
        return filtered

    def scan_ltm_post_write(self, memory_manager):
        """FIXED: Enhanced LTM scanner - scans 100 most recent memories chronologically"""
        if not self.enabled:
            return {'minja_detected': False}

        self.defense_stats['ltm_scans_performed'] += 1

        # Get truly recent entries chronologically (not by similarity)
        ltm_entries = memory_manager.get_recent_ltm_entries(100)
        scan_result = self.cams.scan_ltm_for_minja(ltm_entries)

        # Record scan in history
        scan_record = {
            'timestamp': pd.Timestamp.now(),
            'memories_scanned': len(ltm_entries),
            'minja_detected': scan_result.get('minja_detected', False),
            'bridging_count': scan_result.get('bridging_count', 0),
            'patient_ids_involved': scan_result.get('patient_ids_involved', []),
            'bridging_density': scan_result.get('bridging_density', 0),
            'anomaly_score': scan_result.get('anomaly_score', None)
        }
        self.ltm_scan_history.append(scan_record)

        if scan_result.get('minja_detected'):
            self.defense_stats['minja_patterns_detected'] += 1

            # Quarantine all memories involving targeted patients
            for entry in ltm_entries:
                content = entry.get('content', '')
                reasoning = entry.get('reasoning', '')
                full_text = content + ' ' + reasoning

                # Check if any targeted patient IDs are in this memory
                if any(pid in full_text for pid in scan_result.get('patient_ids_involved', [])):
                    self.quarantine.append({
                        'id': entry.get('metadata', {}).get('id'),
                        'content': entry['content'][:100],
                        'full_content': content,
                        'reasoning': reasoning,
                        'patient_ids': [pid for pid in scan_result.get('patient_ids_involved', []) if pid in full_text],
                        'timestamp': entry.get('timestamp', ''),
                        'reason': 'MINJA pattern detected - bridging attack',
                        'detection_time': pd.Timestamp.now()
                    })

        return scan_result

    def get_ltm_scan_history(self):
        """Get LTM scan history as DataFrame"""
        return pd.DataFrame(self.ltm_scan_history)

    def get_bridging_patterns(self):
        """Get detailed bridging pattern analysis"""
        if not self.ltm_scan_history:
            return None

        # Find all scans with MINJA detections
        minja_scans = [s for s in self.ltm_scan_history if s['minja_detected']]

        if not minja_scans:
            return None

        # Aggregate patient IDs across all detections
        all_patient_ids = []
        for scan in minja_scans:
            all_patient_ids.extend(scan['patient_ids_involved'])

        from collections import Counter
        patient_counts = Counter(all_patient_ids)

        return {
            'total_minja_detections': len(minja_scans),
            'unique_patients_targeted': len(patient_counts),
            'patient_frequency': dict(patient_counts),
            'most_targeted_patients': patient_counts.most_common(5),
            'latest_detection': minja_scans[-1] if minja_scans else None
        }

    def get_stats(self):
        total = self.defense_stats['total_queries']
        if total == 0:
            return self.defense_stats

        return {
            **self.defense_stats,
            'block_rate': (self.defense_stats['minja_blocked'] + self.defense_stats['mextra_blocked']) / total,
            'pass_rate': self.defense_stats['legitimate_passed'] / total
        }

    def get_blocked_log(self):
        return pd.DataFrame(self.blocked_queries_log)

    def get_quarantine_list(self):
        return pd.DataFrame(self.quarantine)

