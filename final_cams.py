class CAMSDefense:
    """Defense layer that wraps around existing EHR Agent"""

    def __init__(self, cams_classifier):
        self.cams = cams_classifier
        self.enabled = False
        self.quarantine = []
        self.blocked_queries_log = []
        self.defense_stats = {
            'total_queries': 0,
            'minja_blocked': 0,
            'mextra_blocked': 0,
            'legitimate_passed': 0,
            'false_positives': 0
        }

    def enable(self):
        """Enable CAMS defense"""
        self.enabled = True
        print("✓ CAMS Defense ENABLED")

    def disable(self):
        """Disable CAMS defense"""
        self.enabled = False
        print("✓ CAMS Defense DISABLED")

    def intercept_query(self, query, patient_id=None):
        """Intercept query before processing"""
        self.defense_stats['total_queries'] += 1

        if not self.enabled:
            return {'allowed': True, 'query': query, 'reason': 'CAMS disabled'}

        # Classify intent
        classification = self.cams.classify_intent(query)

        if classification['blocked']:
            # Log blocked query
            self.blocked_queries_log.append({
                'query': query,
                'intent': classification['intent'],
                'confidence': classification['confidence'],
                'patient_id': patient_id,
                'timestamp': pd.Timestamp.now()
            })

            if classification['intent'] == 'minja':
                self.defense_stats['minja_blocked'] += 1
            elif classification['intent'] == 'mextra':
                self.defense_stats['mextra_blocked'] += 1

            return {
                'allowed': False,
                'blocked': True,
                'intent': classification['intent'],
                'confidence': classification['confidence'],
                'reason': f"Query blocked: Detected {classification['intent'].upper()} attack pattern"
            }

        self.defense_stats['legitimate_passed'] += 1
        return {
            'allowed': True,
            'query': query,
            'intent': classification['intent'],
            'confidence': classification['confidence']
        }

    def filter_retrieval(self, ltm_results, query_classification):
        """Filter LTM retrieval results"""
        if not self.enabled:
            return ltm_results

        # Never retrieve quarantined memories
        filtered = [m for m in ltm_results if m.get('id') not in [q['id'] for q in self.quarantine]]

        # Limit retrieval depth (MEXTRA mitigation)
        if query_classification.get('intent') == 'legitimate':
            filtered = filtered[:5]  # Max 5 memories

        return filtered

    def scan_ltm_post_write(self, memory_manager):
        """Scan LTM after write operations"""
        if not self.enabled:
            return {'minja_detected': False}

        # Get recent LTM entries
        ltm_entries = memory_manager.get_recent_ltm_entries(50)

        # Scan for MINJA
        scan_result = self.cams.scan_ltm_for_minja(ltm_entries)

        if scan_result.get('minja_detected'):
            # Quarantine suspicious memories
            for entry in ltm_entries:
                if any(pid in entry.get('content', '') for pid in scan_result.get('patient_ids_involved', [])):
                    self.quarantine.append({
                        'id': entry.get('metadata', {}).get('id'),
                        'content': entry['content'][:100],
                        'reason': 'MINJA pattern detected'
                    })

        return scan_result

    def get_stats(self):
        """Get defense statistics"""
        total = self.defense_stats['total_queries']
        if total == 0:
            return self.defense_stats

        return {
            **self.defense_stats,
            'block_rate': (self.defense_stats['minja_blocked'] + self.defense_stats['mextra_blocked']) / total,
            'pass_rate': self.defense_stats['legitimate_passed'] / total
        }

    def get_blocked_log(self):
        """Get log of blocked queries"""
        return pd.DataFrame(self.blocked_queries_log)

    def get_quarantine_list(self):
        """Get quarantined memories"""
        return pd.DataFrame(self.quarantine)


